"""
Minimal Microsoft Foundry hosted agent - Responses protocol 2.0.0.

Container contract:
  - Listens on $PORT (default 8088) on 0.0.0.0
  - POST /responses            -> create a response (non-streaming and SSE streaming)
  - GET  /readiness, /liveness -> Foundry hosted-agent health probes
  - GET  /healthz              -> local/Docker health check

Two modes:
  - ECHO mode (default): no model call. Proves the image was pulled from the
    private registry and the container started. Use this for the first deploy.
  - MODEL mode: set AZURE_AI_MODEL_DEPLOYMENT_NAME and the agent relays to that
    deployment through the Foundry project endpoint (FOUNDRY_PROJECT_ENDPOINT,
    injected by the platform) using the agent's own Entra identity.

Knowledge: knowledge/*.md files bundled in the image are added to the model
instructions, so the agent can answer questions about this project. Whole files only,
alphabetical, within MAX_KNOWLEDGE_CHARS; files that don't fit are listed under
"knowledge_truncated" in /healthz. A file can declare extra scope-gate terms with a line
like `<!-- scope: runner, private endpoint -->`.
azure-assets.md is generated by scripts/generate-asset-inventory.ps1; don't hand-edit it.
"""

import json
import os
import re
import time
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, StreamingResponse

APP_NAME = os.getenv("AGENT_NAME", "private-registry-agent")
PORT = int(os.getenv("PORT", "8088"))
MODEL_DEPLOYMENT = os.getenv("AZURE_AI_MODEL_DEPLOYMENT_NAME")
# Injected by Foundry in hosted containers; set it yourself for local runs.
PROJECT_ENDPOINT = os.getenv("FOUNDRY_PROJECT_ENDPOINT")
KNOWLEDGE_DIR = Path(os.getenv("KNOWLEDGE_DIR", Path(__file__).parent / "knowledge"))
# Small, curated files are fine to send in full; switch to file_search if this grows.
MAX_KNOWLEDGE_CHARS = 60_000


def wrap_document(name: str, text: str) -> str:
    return f'<document name="{name}">\n{text}\n</document>'


def load_knowledge() -> Tuple[Dict[str, str], List[str]]:
    """Read each file once. Whole files only, alphabetical, within MAX_KNOWLEDGE_CHARS.

    Returns (name -> text for the files that fit, names of files that were left out).
    """
    if not KNOWLEDGE_DIR.is_dir():
        return {}, []
    docs: Dict[str, str] = {}
    truncated: List[str] = []
    used = 0
    for path in sorted(KNOWLEDGE_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        size = len(wrap_document(path.name, text)) + 2  # + the "\n\n" separator
        if used + size > MAX_KNOWLEDGE_CHARS:
            truncated.append(path.name)
            continue
        docs[path.name] = text
        used += size
    return docs, truncated


def build_instructions(docs: Dict[str, str]) -> str:
    base = f"You are {APP_NAME}, a concise assistant."
    if not docs:
        return base
    joined = "\n\n".join(wrap_document(name, text) for name, text in docs.items())
    return (
        f"{base}\n\n"
        "You also answer questions about this project (Azure, Foundry, Entra ID, JFrog, GitHub, "
        "Terraform, the CI runners and workflows) using the knowledge base below. For "
        "project-specific facts, rely only on the knowledge base and say so when something isn't "
        "covered. IDs are redacted on purpose; never guess or invent them. Documents state when "
        "they were written or generated: mention that date if asked how current the information "
        "is, and if documents disagree, prefer the newer one and say that they differ. Answer "
        "only from the knowledge base. If the question is not about something in it, say so and "
        "do not guess.\n\n"
        f"<knowledge_base>\n{joined}\n</knowledge_base>"
    )


KNOWLEDGE_DOCS, KNOWLEDGE_TRUNCATED = load_knowledge()
INSTRUCTIONS = build_instructions(KNOWLEDGE_DOCS)
if KNOWLEDGE_TRUNCATED:
    print(f"knowledge_truncated={KNOWLEDGE_TRUNCATED} (over {MAX_KNOWLEDGE_CHARS} chars)", flush=True)

app = FastAPI(title=APP_NAME)

_client = None


def get_model_client():
    """Lazily build an OpenAI client for the project endpoint using the agent's Entra identity.

    The hosted-agent identity can call models through the project endpoint by default, so no
    extra role assignment is needed (the identity is platform-managed and can change).
    """
    global _client
    if _client is not None:
        return _client
    if not (MODEL_DEPLOYMENT and PROJECT_ENDPOINT):
        return None
    from azure.identity import DefaultAzureCredential, get_bearer_token_provider
    from openai import OpenAI

    _client = OpenAI(
        base_url=f"{PROJECT_ENDPOINT.rstrip('/')}/openai/v1",
        api_key=get_bearer_token_provider(DefaultAzureCredential(), "https://ai.azure.com/.default"),
    )
    return _client


def flatten_input(payload: Dict[str, Any]) -> str:
    """Accept either input='text' or input=[{role, content:[{type,text}]}]."""
    raw = payload.get("input", "")
    if isinstance(raw, str):
        return raw
    parts: List[str] = []
    if isinstance(raw, list):
        for item in raw:
            if isinstance(item, str):
                parts.append(item)
                continue
            content = item.get("content") if isinstance(item, dict) else None
            if isinstance(content, str):
                parts.append(content)
            elif isinstance(content, list):
                for block in content:
                    if isinstance(block, dict) and block.get("text"):
                        parts.append(block["text"])
    return "\n".join(p for p in parts if p).strip()


# Scope gate: answer only questions that mention an inventory term; checked in code, no model call.
SCOPE_BLOCKED_REPLY = "Not in the knowledge base. Checked by code; the model was not called."
SCOPE_WORDS = {"jfrog", "foundry", "terraform", "github", "entra", "azure", "runner", "tenant",
               "subscription", "repository", "image", "connection", "workflow", "version", "inventory"}
# Too generic to signal scope, even where they appear as backticked names (job/branch names, "@").
SCOPE_EXCLUDED = {"agent", "model", "state", "main", "build", "deploy", "project", "network", "@"}


SCOPE_COMMENT = re.compile(r"<!--\s*scope:(.*?)-->", re.IGNORECASE | re.DOTALL)


def build_scope_terms(docs: Dict[str, str]) -> set:
    if not docs:
        return set()
    names = set()
    declared = set()
    for content in docs.values():
        names.update(n.lower() for n in re.findall(r"`([^`\n]+)`", content))
        names.update(
            key.strip().lower()
            for key in re.findall(r"(?m)^\s*([^#|=\n][^|=\n]*?)\s*=", content)
        )
        for line in SCOPE_COMMENT.findall(content):
            declared.update(t.strip().lower() for t in line.split(",") if t.strip())
    # Terms a file declares explicitly are kept even if they are on the generic-word exclusion list.
    return ((names | SCOPE_WORDS) - SCOPE_EXCLUDED) | declared


def term_in(term: str, text: str) -> bool:
    # Plain words match whole words only; terms with punctuation (hosts, paths) match as substrings.
    if re.fullmatch(r"[a-z0-9]+", term):
        return re.search(rf"\b{term}\b", text) is not None
    return term in text


SCOPE_TERMS = build_scope_terms(KNOWLEDGE_DOCS)

def build_capital_lookup(docs: Dict[str, str]) -> Dict[str, str]:
    capitals: Dict[str, str] = {}
    for content in docs.values():
        in_capital_section = False
        for raw_line in content.splitlines():
            line = raw_line.strip()

            heading = re.fullmatch(r"#{1,6}\s+(.+?)\s*", line)
            if heading:
                in_capital_section = heading.group(1).casefold() == "capital cities"
                continue
            
            if not in_capital_section or not line or "=" not in line: 
                continue
            country, city = (part.strip() for part in line.split("=", 1))
            if not country or not city:
                continue

            normalized_country = country.casefold()
            existing_city = capitals.get(normalized_country)
            if existing_city is not None and existing_city != city:
                raise ValueError(f"Conflicting city for country {country}: {existing_city} vs {city}")
            capitals[normalized_country] = city

    return capitals

CAPITALS = build_capital_lookup(KNOWLEDGE_DOCS)

def answer_capital_question(prompt: str) -> Optional[str]:
    normalized_prompt = prompt.casefold()

    if re.search(r"\bcapital\b", normalized_prompt) is None:
        return None

    matches = [
        (country,city)
        for country,city in CAPITALS.items()
        if term_in(country, normalized_prompt)
    ]
    if not matches:
        return SCOPE_BLOCKED_REPLY

    matches.sort(key=lambda item: len(item[0]), reverse=True)
    return "\n".join(
        f"The capital of {country.title()} is {city}."
        for country, city in matches
    )

def answer(prompt: str) -> str:
    capital_answer = answer_capital_question(prompt)
    if capital_answer is not None:
        print("scope_gate=capital_lookup", flush=True)
        return capital_answer
    
    in_scope = any(term_in(term, prompt.lower()) for term in SCOPE_TERMS)
    print(f"scope_gate={'pass' if in_scope else 'blocked'}", flush=True)
    if not in_scope:
        return SCOPE_BLOCKED_REPLY
    client = get_model_client()
    if client is None:
        return (
            f"[{APP_NAME}] Hosted agent is running from a private registry image. "
            f"Echo mode (no model deployment configured). You said: {prompt!r}"
        )
    # Reasoning models (gpt-5 family) reject legacy sampling parameters, so none are sent.
    result = client.responses.create(model=MODEL_DEPLOYMENT, instructions=INSTRUCTIONS, input=prompt)
    return result.output_text or ""


def envelope(text: str, response_id: str, status: str = "completed") -> Dict[str, Any]:
    """Responses-shaped payload: output[] + the output_text convenience field."""
    return {
        "id": response_id,
        "object": "response",
        "created_at": int(time.time()),
        "status": status,
        "model": MODEL_DEPLOYMENT or "echo",
        "output": [
            {
                "id": f"msg_{uuid.uuid4().hex[:16]}",
                "type": "message",
                "role": "assistant",
                "status": "completed",
                "content": [{"type": "output_text", "text": text, "annotations": []}],
            }
        ],
        "output_text": text,
    }


@app.get("/healthz")
@app.get("/readiness")
@app.get("/liveness")
def healthz():
    return {
        "status": "ok",
        "agent": APP_NAME,
        "mode": "model" if MODEL_DEPLOYMENT else "echo",
        "knowledge": list(KNOWLEDGE_DOCS),
        "knowledge_truncated": KNOWLEDGE_TRUNCATED,
    }


@app.post("/responses")
async def create_response(request: Request):
    payload: Dict[str, Any] = await request.json()
    prompt = flatten_input(payload)
    response_id = f"resp_{uuid.uuid4().hex[:24]}"

    try:
        text = answer(prompt)
    except Exception as exc:  # surface failures as a protocol error, not a 500 wall
        return JSONResponse(
            status_code=200,
            content={
                "id": response_id,
                "object": "response",
                "status": "failed",
                "error": {"code": "agent_error", "message": str(exc)},
            },
        )

    if not payload.get("stream"):
        return JSONResponse(content=envelope(text, response_id))

    def sse():
        created = envelope(text, response_id, status="in_progress")
        yield f"event: response.created\ndata: {json.dumps(created)}\n\n"
        yield (
            "event: response.output_text.delta\n"
            f"data: {json.dumps({'type': 'response.output_text.delta', 'delta': text})}\n\n"
        )
        done = envelope(text, response_id)
        yield f"event: response.completed\ndata: {json.dumps({'type': 'response.completed', 'response': done})}\n\n"

    return StreamingResponse(sse(), media_type="text/event-stream")


# Some hosts probe the versioned path; keep an alias so either works.
@app.post("/v1/responses")
async def create_response_v1(request: Request):
    return await create_response(request)


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(app, host="0.0.0.0", port=PORT)
